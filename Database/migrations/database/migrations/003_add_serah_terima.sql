COMMENT ON COLUMN serah_terima.nama_penerima IS
    'Snapshot nama mahasiswa pemilik klaim pada saat penyerahan.';

-- Validasi sebelum penyerahan dicatat.
-- Syarat:
-- 1. Klaim harus ditemukan dan berstatus disetujui.
-- 2. Klaim harus terkait dengan laporan jenis temuan.
-- 3. Laporan temuan harus sedang diproses (siap diserahkan).
-- 4. Petugas harus memiliki role petugas/admin dan akun aktif.
-- 5. Pos penyerahan harus aktif.
-- 6. Nama penerima diambil dari akun pemilik klaim, bukan dipercaya dari input form.
CREATE OR REPLACE FUNCTION fn_validasi_serah_terima()
RETURNS TRIGGER AS $$
DECLARE
    v_status_klaim VARCHAR(20);
    v_jenis_laporan VARCHAR(10);
    v_status_laporan VARCHAR(20);
    v_nama_penerima VARCHAR(100);
    v_role_petugas VARCHAR(20);
    v_petugas_aktif BOOLEAN;
    v_pos_aktif BOOLEAN;
BEGIN
    SELECT
        k.status_verifikasi,
        p.jenis,
        p.status,
        pemilik.nama
    INTO
        v_status_klaim,
        v_jenis_laporan,
        v_status_laporan,
        v_nama_penerima
    FROM klaim k
    JOIN pengumuman p
        ON p.id_pengumuman = k.id_pengumuman
    JOIN pengguna pemilik
        ON pemilik.id_pengguna = k.id_pengguna
    WHERE k.id_klaim = NEW.id_klaim
    FOR UPDATE OF k, p;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Klaim untuk penyerahan tidak ditemukan.';
    END IF;

    IF v_status_klaim IS DISTINCT FROM 'disetujui' THEN
        RAISE EXCEPTION 'Penyerahan hanya dapat dilakukan untuk klaim yang sudah disetujui.';
    END IF;

    IF v_jenis_laporan IS DISTINCT FROM 'temuan' THEN
        RAISE EXCEPTION 'Penyerahan hanya berlaku untuk laporan barang temuan.';
    END IF;

    IF v_status_laporan IS DISTINCT FROM 'diproses' THEN
        RAISE EXCEPTION 'Laporan harus berstatus diproses sebelum penyerahan dicatat.';
    END IF;

    SELECT role, is_active
    INTO v_role_petugas, v_petugas_aktif
    FROM pengguna
    WHERE id_pengguna = NEW.id_petugas;

    IF NOT FOUND
       OR v_role_petugas NOT IN ('petugas', 'admin')
       OR v_petugas_aktif IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION 'Pencatatan penyerahan harus dilakukan oleh akun petugas/admin yang aktif.';
    END IF;

    SELECT is_active
    INTO v_pos_aktif
    FROM pos_penyerahan
    WHERE id_pos = NEW.id_pos;

    IF NOT FOUND OR v_pos_aktif IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION 'Pos penyerahan tidak ditemukan atau sedang tidak aktif.';
    END IF;

    -- Gunakan nama dari akun mahasiswa yang mengajukan klaim.
    NEW.nama_penerima := v_nama_penerima;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_validasi_serah_terima_insert
BEFORE INSERT ON serah_terima
FOR EACH ROW
EXECUTE FUNCTION fn_validasi_serah_terima();

