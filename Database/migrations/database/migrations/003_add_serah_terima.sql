CREATE TABLE serah_terima (
    id_serah_terima INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_klaim INTEGER NOT NULL
        REFERENCES klaim(id_klaim) ON DELETE RESTRICT,

    id_petugas INTEGER NOT NULL
        REFERENCES pengguna(id_pengguna) ON DELETE RESTRICT,

    id_pos INTEGER NOT NULL
        REFERENCES pos_penyerahan(id_pos) ON DELETE RESTRICT,

    -- Snapshot nama penerima saat barang diserahkan.
    -- Nilainya akan diisi ulang oleh trigger berdasarkan pemilik klaim.
    nama_penerima VARCHAR(100) NOT NULL,

    tanggal_serah_terima TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    catatan TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_serah_terima_klaim UNIQUE (id_klaim),
    CONSTRAINT chk_serah_terima_nama_penerima
        CHECK (LENGTH(BTRIM(nama_penerima)) > 0)
);

CREATE INDEX idx_serah_terima_petugas
    ON serah_terima(id_petugas);

CREATE INDEX idx_serah_terima_pos
    ON serah_terima(id_pos);

CREATE INDEX idx_serah_terima_tanggal
    ON serah_terima(tanggal_serah_terima DESC);

